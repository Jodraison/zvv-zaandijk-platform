function withLinks(list: DecisionLabSession[]): DecisionLabSession[] {
  return list.map((s, i) => ({
    ...s,
    prevSessionId: i > 0 ? list[i - 1]!.id : null,
    nextSessionId: i < list.length - 1 ? list[i + 1]!.id : null,
  }));
}

const COMBINED = withLinks([
  ...DECISION_LAB_SESSIONS,
  ...REST.map((s) => ({ ...s, prevSessionId: null, nextSessionId: null })),
]);

export function listDecisionLabSessions(): DecisionLabSession[] {
  return COMBINED;
}

export function getDecisionLabSession(idOrSlug: string): DecisionLabSession | undefined {
  return COMBINED.find((s) => s.id === idOrSlug || s.slug === idOrSlug);
}

export function listDecisionLabSessionParams(): { sessionId: string }[] {
  return COMBINED.map((s) => ({ sessionId: s.slug }));
}

