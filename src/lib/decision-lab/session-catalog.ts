/** Dedicated film pitch wiring — no generic press-good / connected-team fallback. */
function dedicatedPitch(
  slug: string,
  titles: {
    badTitle: string;
    goodTitle: string;
    badConsequence?: string;
    goodConsequence?: string;
  },
) {
  const ids = filmIdsForSlug(slug);
  return {
    liveSituationId: ids.live,
    badSituationId: ids.bad,
    goodSituationId: ids.good,
    badTitle: titles.badTitle,
    goodTitle: titles.goodTitle,
    badConsequence:
      titles.badConsequence ?? "Verkeerde prioriteit — ruimte of timing valt tegen ons.",
    goodConsequence:
      titles.goodConsequence ?? "Juiste prioriteit — team blijft speelbaar.",
  } as const;
}

